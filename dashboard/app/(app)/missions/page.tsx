function briefToMarkdown(m: Mission): string {
  const r = m.result;
  if (!r) return "";
  const lines = [`# ${r.headline}`, "", `> Goal: ${m.goal}`, "", r.summary, ""];
  if (r.sections.length) {
    lines.push("## Findings", "");
    for (const sec of r.sections) lines.push(`- **${sec.title}** (${sec.agent}): ${sec.body}`);
    lines.push("");
  }
  if (r.sources.length) {
    lines.push("## Sources", "");
    for (const src of r.sources) lines.push(`- [${src.name}](${src.url})`);
    lines.push("");
  }
  lines.push(`_Generated by AgencyForge (${r.writtenBy === "llm" ? `LLM: ${r.provider ?? "unknown"}` : "template writer"})._`);
  return lines.join("\n");
}

const STAGE_ICONS: Record<MissionStage["name"], React.ComponentType<{ className?: string }>> = {
  plan: ListChecks,
  assign: Users,
  execute: Cog,
  respond: FileText,
};

const STAGE_HELP: Record<MissionStage["name"], string> = {
  plan: "Break the goal into tasks",
  assign: "Pick an agent and a tool for each task",
  execute: "Agents call live data sources in parallel",
  respond: "Write the executive brief",
};

const AGENT_LABEL: Record<string, string> = {
  research: "Research Agent",
  analytics: "Analytics Expert",
  marketing: "Marketing Agent",
  content: "Content Strategist",
  ceo: "CEO",
};

const FALLBACK_TEMPLATES: MissionTemplate[] = [
  {
    id: "market-brief",
    title: "Market brief",
    description: "Background research, a market profile and live tech trends.",
    goal: "Research the dental clinic market in Germany and brief me on the country and tech trends",
    agents: ["research", "marketing", "content"],
  },
  {
    id: "trend-radar",
    title: "Trend radar",
    description: "What the tech community is talking about right now.",
    goal: "Scan today’s top tech trends for AI agents",
    agents: ["research", "content"],
  },
];

function stageTone(status: MissionStage["status"]): string {
  switch (status) {
    case "done":
      return "border-emerald-200 bg-emerald-50 text-emerald-600";
    case "running":
      return "border-emerald-300 bg-white text-emerald-600 ring-4 ring-emerald-100";
    case "failed":
      return "border-rose-200 bg-rose-50 text-rose-600";
    default:
      return "border-neutral-200 bg-white/70 text-neutral-300";
  }
}

function Stepper({ stages }: { stages: MissionStage[] }) {
  return (
    <ol className="grid grid-cols-2 gap-3 md:grid-cols-4">
      {stages.map((stage, i) => {
        const Icon = STAGE_ICONS[stage.name];
        return (
          <li key={stage.name} className="relative">
            <div className="flex items-center gap-3">
              <span
                className={cn(
                  "flex h-11 w-11 flex-shrink-0 items-center justify-center rounded-2xl border transition-all",
                  stageTone(stage.status),
                )}
              >
                {stage.status === "running" ? (
                  <Loader2 className="h-5 w-5 animate-spin" />
                ) : stage.status === "done" ? (
                  <CheckCircle2 className="h-5 w-5" />
                ) : stage.status === "failed" ? (
                  <XCircle className="h-5 w-5" />
                ) : (
                  <Icon className="h-5 w-5" />
                )}
              </span>
              <div className="min-w-0">
                <p className="text-[11px] font-bold uppercase tracking-wider text-neutral-400">Stage {i + 1}</p>
                <p className="text-[15px] font-extrabold leading-tight text-neutral-900">{stage.label}</p>
              </div>
            </div>
            <p className="mt-2 text-xs font-medium leading-snug text-neutral-500">
              {stage.detail ?? STAGE_HELP[stage.name]}
            </p>
          </li>
        );
      })}
    </ol>
  );
}

function TaskCard({ task }: { task: MissionTask }) {
  const emotion =
    task.status === "running" ? "working" : task.status === "done" ? "happy" : task.status === "failed" ? "worried" : "idle";
  return (
    <motion.li
      layout
      initial={{ opacity: 0, y: 12 }}
      animate={{ opacity: 1, y: 0 }}
      className="flex gap-4 rounded-2xl border border-white/80 bg-white/60 p-4 shadow-sm"
    >
      <CharacterRenderer department={task.agent} emotion={emotion} size="lg" className="flex-shrink-0" />
      <div className="min-w-0 flex-1">
        <div className="flex flex-wrap items-center gap-2">
          <span className="text-[11px] font-bold uppercase tracking-wider text-neutral-400">
            {AGENT_LABEL[task.agent] ?? task.agent}
          </span>
          <span
            className={cn(
              "rounded-full px-2 py-0.5 text-[10px] font-bold uppercase",
              task.status === "done" && "bg-emerald-100 text-emerald-700",
              task.status === "running" && "bg-sky-100 text-sky-700",
              task.status === "failed" && "bg-rose-100 text-rose-700",
              task.status === "pending" && "bg-neutral-100 text-neutral-500",
            )}
          >
            {task.status}
          </span>
          {task.durationMs != null && task.status !== "pending" && (
            <span className="flex items-center gap-1 text-[11px] font-medium text-neutral-400">
              <Clock className="h-3 w-3" />
              {(task.durationMs / 1000).toFixed(1)}s
            </span>
          )}
        </div>
        <h3 className="mt-1 text-[15px] font-extrabold leading-snug text-neutral-900">{task.title}</h3>
        {task.status === "done" && task.summary && (
          <p className="mt-1.5 text-[13px] font-medium leading-relaxed text-neutral-600">{task.summary}</p>
        )}
        {task.status === "failed" && task.error && (
          <p className="mt-1.5 text-[13px] font-medium leading-relaxed text-rose-600">{task.error}</p>
        )}
        {task.sourceUrl && task.status === "done" && (
          <a
            href={task.sourceUrl}
            target="_blank"
            rel="noreferrer"
            className="mt-2 inline-flex items-center gap-1 text-xs font-bold text-emerald-700 hover:underline"
          >
            {task.sourceName ?? "Source"} <ExternalLink className="h-3 w-3" />
          </a>
        )}
      </div>
    </motion.li>
  );
}

export default function MissionsPage() {
  const [goal, setGoal] = React.useState("");
  const [useAi, setUseAi] = React.useState(true);
  const [templates, setTemplates] = React.useState<MissionTemplate[]>([]);
  const [history, setHistory] = React.useState<Mission[]>([]);
  const [mission, setMission] = React.useState<Mission | null>(null);
  const [online, setOnline] = React.useState<boolean | null>(null);
  const [launching, setLaunching] = React.useState(false);
  const [error, setError] = React.useState<string | null>(null);
  const [autoRun, setAutoRun] = React.useState(false);
  const [copied, setCopied] = React.useState(false);
  const pollRef = React.useRef<ReturnType<typeof setInterval> | null>(null);

  const stopPolling = React.useCallback(() => {
    if (pollRef.current) {
      clearInterval(pollRef.current);
      pollRef.current = null;
    }
  }, []);

  const refreshHistory = React.useCallback(async () => {
    try {
      const res = await runtimeJson<{ missions: Mission[] }>(RUNTIME_ENDPOINTS.missions);
      setHistory(res.missions.slice(0, 6));
      setOnline(true);
    } catch {
      setOnline(false);
    }
  }, []);

  const poll = React.useCallback(
    (id: string) => {
      stopPolling();
      pollRef.current = setInterval(async () => {
        try {
          const m = await runtimeJson<Mission>(`${RUNTIME_ENDPOINTS.missions}/${id}`);
          setMission(m);
          if (isFinished(m)) {
            stopPolling();
            void refreshHistory();
          }
        } catch (e) {
          stopPolling();
          setError(e instanceof Error ? e.message : "Lost connection to the runtime");
        }
      }, 600);
    },
    [refreshHistory, stopPolling],
  );

  React.useEffect(() => {
    let cancelled = false;
    (async () => {
      let list = FALLBACK_TEMPLATES;
      try {
        const res = await runtimeJson<{ templates: MissionTemplate[] }>(RUNTIME_ENDPOINTS.missionTemplates);
        list = res.templates;
        if (!cancelled) setOnline(true);
      } catch {
        if (!cancelled) setOnline(false);
      }
      if (cancelled) return;
      setTemplates(list);

      const params = new URLSearchParams(window.location.search);
      const wanted = params.get("template");
      const prefill = params.get("goal") ?? list.find((t) => t.id === wanted)?.goal;
      if (prefill) setGoal(prefill);
      if (prefill && params.get("run") === "1") setAutoRun(true);
    })();
    void refreshHistory();
    return () => {
      cancelled = true;
      stopPolling();
    };
  }, [refreshHistory, stopPolling]);

  async function launch() {
    const text = goal.trim();
    if (text.length < 3 || launching) return;
    setLaunching(true);
    setError(null);
    try {
      const created = await runtimeJson<Mission>(RUNTIME_ENDPOINTS.missions, {
        method: "POST",
        body: { goal: text, llm: useAi },
      });
      setMission(created);
      setOnline(true);
      poll(created.id);
    } catch (e) {
      setOnline(false);
      setError(e instanceof Error ? e.message : "Could not start the mission");
    } finally {
      setLaunching(false);
    }
  }

  React.useEffect(() => {
    if (autoRun && goal.trim().length >= 3) {
      setAutoRun(false);
      void launch();
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [autoRun, goal]);

  const running = mission !== null && !isFinished(mission);

  return (
    <div className="mx-auto max-w-[1100px] space-y-6 p-6 lg:p-8">
      <PageHeader
        icon={<Rocket className="h-6 w-6" />}
        title="Missions"
        subtitle="Give your AI team a goal. Watch the plan, the hand-offs and the result."
        actions={
          online === false ? (
            <span className="flex items-center gap-1.5 rounded-full bg-rose-50 px-3 py-1.5 text-xs font-bold text-rose-600">
              <WifiOff className="h-3.5 w-3.5" /> Runtime offline
            </span>
          ) : online ? (
            <span className="flex items-center gap-1.5 rounded-full bg-emerald-50 px-3 py-1.5 text-xs font-bold text-emerald-700">
              <span className="h-2 w-2 rounded-full bg-emerald-500" /> Runtime online
            </span>
          ) : null
        }
      />

      {/* composer */}
      <Surface className="space-y-4 p-5">
        <label htmlFor="mission-goal" className="text-[13px] font-extrabold text-neutral-800">
          What should your team achieve?
        </label>
        <textarea
          id="mission-goal"
          value={goal}
          onChange={(e) => setGoal(e.target.value)}
          onKeyDown={(e) => {
            if (e.key === "Enter" && (e.metaKey || e.ctrlKey)) void launch();
          }}
          rows={2}
          maxLength={500}
          placeholder="e.g. Plan an outdoor coffee pop-up launch in Lisbon and check the weather"
          className="w-full resize-none rounded-2xl border border-black/10 bg-white/80 px-4 py-3 text-[15px] font-medium text-neutral-900 outline-none transition placeholder:text-neutral-400 focus:border-emerald-400 focus:ring-4 focus:ring-emerald-100"
        />
        <div className="flex flex-wrap items-center justify-between gap-3">
          <div className="flex flex-wrap gap-2">
            {(templates.length ? templates : FALLBACK_TEMPLATES).map((t) => (
              <button
                key={t.id}
                type="button"
                title={t.description}
                onClick={() => setGoal(t.goal)}
                className="rounded-full border border-black/10 bg-white/70 px-3 py-1.5 text-xs font-bold text-neutral-700 transition hover:border-emerald-300 hover:bg-emerald-50 hover:text-emerald-700"
              >
                {t.title}
              </button>
            ))}
          </div>
          <div className="flex items-center gap-4">
            <label className="flex cursor-pointer items-center gap-2 text-xs font-bold text-neutral-600">
              <input
                type="checkbox"
                checked={useAi}
                onChange={(e) => setUseAi(e.target.checked)}
                className="h-4 w-4 accent-emerald-500"
              />
              Let an LLM write the brief
            </label>
            <button
              type="button"
              onClick={() => void launch()}
              disabled={goal.trim().length < 3 || launching || running}
              className="inline-flex items-center gap-2 rounded-2xl bg-gradient-to-r from-emerald-500 to-teal-500 px-5 py-2.5 text-sm font-extrabold text-white shadow-lg shadow-emerald-500/25 transition hover:from-emerald-600 hover:to-teal-600 disabled:cursor-not-allowed disabled:opacity-50"
            >
              {launching || running ? <Loader2 className="h-4 w-4 animate-spin" /> : <Rocket className="h-4 w-4" />}
              {running ? "Mission running…" : "Launch mission"}
            </button>
          </div>
        </div>
        {error && (
          <p className="rounded-xl bg-rose-50 px-3 py-2 text-xs font-semibold text-rose-600">
            {error}
            {online === false && <> Start the runtime with <code className="font-mono">pnpm start:runtime</code>.</>}
          </p>
        )}
      </Surface>

      {/* live pipeline */}
      {mission ? (
        <div className="space-y-6">
          <Surface className="space-y-5 p-5">
            <div className="flex flex-wrap items-center justify-between gap-2">
              <div className="min-w-0">
                <p className="text-[11px] font-bold uppercase tracking-wider text-neutral-400">Mission {mission.id}</p>
                <h2 className="truncate text-[17px] font-extrabold text-neutral-900">{mission.goal}</h2>
              </div>
              {mission.plannedBy && (
                <span className="rounded-full bg-neutral-100 px-3 py-1 text-[11px] font-bold text-neutral-600">
                  {mission.plannedBy === "llm" ? "Planned by an LLM" : "Planned by built-in rules"}
                </span>
              )}
              <span
                className={cn(
                  "rounded-full px-3 py-1 text-xs font-extrabold uppercase",
                  mission.status === "completed" && "bg-emerald-100 text-emerald-700",
                  mission.status === "failed" && "bg-rose-100 text-rose-700",
                  !isFinished(mission) && "bg-sky-100 text-sky-700",
                )}
              >
                {mission.status}
              </span>
            </div>
            <Stepper stages={mission.stages} />
          </Surface>

          {mission.tasks.length > 0 && (
            <section aria-label="Tasks">
              <h2 className="mb-3 text-[15px] font-extrabold text-neutral-900">Team activity</h2>
              <ul className="grid grid-cols-1 gap-3 lg:grid-cols-2">
                <AnimatePresence>
                  {mission.tasks.map((t) => (
                    <TaskCard key={t.id} task={t} />
                  ))}
                </AnimatePresence>
              </ul>
            </section>
          )}

          {mission.status === "failed" && mission.error && (
            <Surface className="border-rose-200 p-5">
              <p className="text-sm font-bold text-rose-700">Mission failed</p>
              <p className="mt-1 text-sm font-medium text-rose-600">{mission.error}</p>
            </Surface>
          )}

          {mission.result && (
            <Surface className="space-y-4 p-6">
              <div className="flex flex-wrap items-center justify-between gap-2">
                <div className="flex items-center gap-3">
                  <CharacterRenderer department="ceo" emotion="celebrating" size="lg" />
                  <div>
                    <p className="text-[11px] font-bold uppercase tracking-wider text-emerald-600">Executive brief</p>
                    <h2 className="text-xl font-extrabold text-neutral-900">{mission.result.headline}</h2>
                  </div>
                </div>
                <button
                  type="button"
                  onClick={async () => {
                    try {
                      await navigator.clipboard.writeText(briefToMarkdown(mission));
                      setCopied(true);
                      setTimeout(() => setCopied(false), 1800);
                    } catch {
                      setError("Could not copy to the clipboard");
                    }
                  }}
                  className="inline-flex items-center gap-1.5 rounded-full border border-black/10 bg-white/80 px-3 py-1 text-[11px] font-bold text-neutral-700 transition hover:border-emerald-300 hover:bg-emerald-50"
                >
                  {copied ? <Check className="h-3 w-3 text-emerald-600" /> : <Copy className="h-3 w-3" />}
                  {copied ? "Copied" : "Copy as Markdown"}
                </button>
                <span className="inline-flex items-center gap-1.5 rounded-full bg-neutral-100 px-3 py-1 text-[11px] font-bold text-neutral-600">
                  <Sparkles className="h-3 w-3" />
                  {mission.result.writtenBy === "llm"
                    ? `Written by ${mission.result.provider ?? "an LLM"}`
                    : "Written by built-in template (no LLM configured)"}
                </span>
              </div>
              <p className="text-[15px] font-medium leading-relaxed text-neutral-700">{mission.result.summary}</p>
              {mission.result.sources.length > 0 && (
                <div className="flex flex-wrap items-center gap-2 border-t border-black/5 pt-4">
                  <span className="text-xs font-bold text-neutral-400">Sources</span>
                  {mission.result.sources.map((s) => (
                    <a
                      key={s.url}
                      href={s.url}
                      target="_blank"
                      rel="noreferrer"
                      className="inline-flex items-center gap-1 rounded-full bg-emerald-50 px-3 py-1 text-xs font-bold text-emerald-700 hover:bg-emerald-100"
                    >
                      {s.name} <ExternalLink className="h-3 w-3" />
                    </a>
                  ))}
                </div>
              )}
            </Surface>
          )}

          {mission.suggestedApis.length > 0 && (
            <Surface className="space-y-3 p-5">
              <div className="flex items-center justify-between">
                <h2 className="flex items-center gap-2 text-[15px] font-extrabold text-neutral-900">
                  <Library className="h-4 w-4 text-emerald-600" /> More free APIs your agents could use
                </h2>
                <Link href="/apis" className="text-xs font-bold text-emerald-700 hover:underline">
                  Open API Explorer
                </Link>
              </div>
              <ul className="grid grid-cols-1 gap-2 sm:grid-cols-2">
                {mission.suggestedApis.map((api) => (
                  <li key={api.url}>
                    <a
                      href={api.url}
                      target="_blank"
                      rel="noreferrer"
                      className="block rounded-xl border border-black/5 bg-white/70 p-3 transition hover:border-emerald-200 hover:bg-white"
                    >
                      <p className="text-sm font-extrabold text-neutral-800">{api.name}</p>
                      <p className="mt-0.5 line-clamp-1 text-xs font-medium text-neutral-500">{api.description}</p>
                      <p className="mt-1 text-[10px] font-bold uppercase tracking-wider text-neutral-400">{api.category}</p>
                    </a>
                  </li>
                ))}
              </ul>
            </Surface>
          )}
        </div>
      ) : (
        <Surface className="p-6">
          <h2 className="text-[15px] font-extrabold text-neutral-900">How a mission works</h2>
          <div className="mt-4">
            <Stepper
              stages={(["plan", "assign", "execute", "respond"] as const).map((name) => ({
                name,
                label: name.charAt(0).toUpperCase() + name.slice(1),
                status: "pending" as const,
              }))}
            />
          </div>
          <p className="mt-5 text-[13px] font-medium leading-relaxed text-neutral-500">
            Missions run on live, key-less public APIs (Wikipedia, Open-Meteo, World Bank, Hacker News), so they work
            on a fresh install. Add an LLM key or run the 9Router gateway and the brief is written by a model instead
            of a template.
          </p>
        </Surface>
      )}

      {/* history */}
      {history.length > 0 && (
        <section aria-label="Recent missions">
          <h2 className="mb-3 text-[15px] font-extrabold text-neutral-900">Recent missions</h2>
          <ul className="grid grid-cols-1 gap-2 md:grid-cols-2">
            {history.map((m) => (
              <li key={m.id}>
                <button
                  type="button"
                  onClick={() => {
                    setMission(m);
                    if (!isFinished(m)) poll(m.id);
                  }}
                  className="flex w-full items-center justify-between gap-3 rounded-2xl border border-white/80 bg-white/55 px-4 py-3 text-left transition hover:bg-white"
                >
                  <span className="truncate text-sm font-bold text-neutral-800">{m.goal}</span>
                  <span
                    className={cn(
                      "flex-shrink-0 rounded-full px-2 py-0.5 text-[10px] font-extrabold uppercase",
                      m.status === "completed" && "bg-emerald-100 text-emerald-700",
                      m.status === "failed" && "bg-rose-100 text-rose-700",
                      !isFinished(m) && "bg-sky-100 text-sky-700",
                    )}
                  >
                    {m.status}
                  </span>
                </button>
              </li>
            ))}
          </ul>
        </section>
      )}
    </div>
  );
}
